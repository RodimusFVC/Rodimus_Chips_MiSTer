#!/usr/bin/env python3
"""Build the authoritative opcode map by replaying MAME's own table-init loop.

Reads MAME's unmodified z8000tbl.hxx and reproduces exactly what
z8002_device::init_tables() does:

    for (const Z8000_init *opc = table; opc->size; opc++)
        for (u32 val = opc->beg; val <= opc->end; val += opc->step)
            z8000_exec[val] = opc - table;

so later entries overwrite earlier ones, and entry 0 (zinvalid, 0x0000-0xffff)
is the fallback for everything never overwritten. The result is a per-first-word
handler name / size / cycles map used to
  * decide which opcodes are testable at all (handler != zinvalid), and
  * group results by instruction family in the report.

Output: z8000_opinfo.h  (generated; do not edit by hand)
"""

import re
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SUITE = os.path.dirname(HERE)
DEFAULT_TBL = os.path.abspath(os.path.join(
    SUITE, "..", "..", "Useful Stuff", "mame", "z8000", "z8000tbl.hxx"))

ENTRY_RE = re.compile(
    r"\{\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*,\s*(\d+)\s*,"
    r"\s*(\d+)\s*,\s*(\d+)\s*,\s*&z8002_device::([A-Za-z0-9_]+)\s*\}")


def main():
    tbl_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_TBL
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(SUITE, "z8000_opinfo.h")

    with open(tbl_path) as f:
        text = f.read()

    entries = []
    for m in ENTRY_RE.finditer(text):
        beg, end, step, size, cycles, name = m.groups()
        entries.append(dict(beg=int(beg, 0), end=int(end, 0), step=int(step),
                            size=int(size), cycles=int(cycles), name=name))

    if not entries:
        sys.exit("no table entries parsed from %s" % tbl_path)

    # MAME stops at the first entry with size == 0 (the terminator row).
    stop = next((i for i, e in enumerate(entries) if e["size"] == 0), len(entries))
    entries = entries[:stop]

    exec_map = [0] * 0x10000
    for idx, e in enumerate(entries):
        val = e["beg"]
        while val <= e["end"]:
            exec_map[val] = idx
            val += e["step"]

    n_valid = sum(1 for v in exec_map if entries[v]["name"] != "zinvalid")

    with open(out_path, "w") as f:
        f.write("// GENERATED by tools/gen_opinfo.py from MAME's z8000tbl.hxx -- do not edit.\n")
        f.write("// %d table entries; %d of 65536 first words decode to a real instruction.\n"
                % (len(entries), n_valid))
        f.write("#ifndef Z8000_OPINFO_H\n#define Z8000_OPINFO_H\n\n")
        f.write("#include <cstdint>\n\n")
        f.write("struct z8k_opinfo { const char *name; uint8_t size; uint16_t cycles; };\n\n")
        f.write("static const z8k_opinfo z8k_opinfo_tbl[] = {\n")
        for e in entries:
            f.write('    { "%s", %d, %d },\n' % (e["name"], e["size"], e["cycles"]))
        f.write("};\n\n")
        f.write("static const uint16_t z8k_opinfo_index[0x10000] = {\n")
        for i in range(0, 0x10000, 16):
            f.write("    " + ",".join("%d" % v for v in exec_map[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static inline const z8k_opinfo &z8k_op(uint16_t w)\n"
                "{ return z8k_opinfo_tbl[z8k_opinfo_index[w]]; }\n\n")
        f.write("#endif // Z8000_OPINFO_H\n")

    print("%s: %d entries, %d/65536 valid first words, %d distinct handlers"
          % (os.path.basename(out_path), len(entries), n_valid,
             len({e["name"] for e in entries})))


if __name__ == "__main__":
    main()
