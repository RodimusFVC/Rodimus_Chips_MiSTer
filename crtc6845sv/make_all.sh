#!/bin/sh
# Regenerate rtl/crtc6845sv_all.sv: core + every drop-in / variant top + the VDC (not the chip_pool_pkg wrapper).
cd "$(dirname "$0")/rtl"
{
  echo "// crtc6845sv_all.sv: generated by make_all.sh from rtl/*.sv (core + drop-in + variant tops + VDC)."
  for f in crtc6845sv.sv crtc6845sv_mc6845.sv crtc6845sv_mc6845_motorola.sv crtc6845sv_hd6845s.sv crtc6845sv_um6845r.sv \
           crtc6845sv_ams40489.sv crtc6845sv_ams40226.sv crtc6845sv_r6545.sv crtc6845sv_mos6545.sv crtc6845sv_vdc.sv; do
    echo; echo "// ---- $f"; cat "$f"
  done
} > crtc6845sv_all.sv
echo "rtl/crtc6845sv_all.sv: $(wc -l < crtc6845sv_all.sv) lines"
