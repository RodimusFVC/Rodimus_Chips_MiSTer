// gen_tables.cpp: emit MAME's TMS5220 coefficient tables (tms5110r.hxx, tms5220_coeff) as a Verilog include.
#include <cstdio>
#include <cstdint>
#include "mame_src/tms5110r.hxx"
int main()
{
    const tms5100_coeffs &c = tms5220_coeff;
    printf("// GENERATED by gen_tables.cpp from MAME tms5110r.hxx tms5220_coeff -- do not edit\n");
    printf("// num_k %d energy_bits %d pitch_bits %d kbits", c.num_k, c.energy_bits, c.pitch_bits);
    for (int i = 0; i < 10; i++) printf(" %d", c.kbits[i]);
    printf("\nfunction automatic [9:0] t5220_energy(input [3:0] i);\n  case (i)\n");
    for (int i = 0; i < 16; i++) printf("    4'd%d: t5220_energy = 10'd%d;\n", i, c.energytable[i]);
    printf("  endcase\nendfunction\n");
    printf("function automatic [9:0] t5220_pitch(input [5:0] i);\n  case (i)\n");
    for (int i = 0; i < 64; i++) printf("    6'd%d: t5220_pitch = 10'd%d;\n", i, c.pitchtable[i]);
    printf("  endcase\nendfunction\n");
    printf("// k table: index {k[3:0], idx[4:0]}; signed 10-bit\n");
    printf("function automatic signed [9:0] t5220_k(input [3:0] k, input [4:0] i);\n  case ({k, i})\n");
    for (int k = 0; k < 10; k++)
        for (int i = 0; i < (1 << c.kbits[k]); i++)
            printf("    {4'd%d, 5'd%d}: t5220_k = %s10'sd%d;\n", k, i, c.ktable[k][i] < 0 ? "-" : "", c.ktable[k][i] < 0 ? -c.ktable[k][i] : c.ktable[k][i]);
    printf("    default: t5220_k = 10'sd0;\n  endcase\nendfunction\n");
    printf("function automatic signed [7:0] t5220_chirp(input [5:0] i);\n  case (i)\n");
    for (int i = 0; i < 52; i++) printf("    6'd%d: t5220_chirp = 8'h%02X;\n", i, (uint8_t)c.chirptable[i]);
    printf("    default: t5220_chirp = 8'h00;\n  endcase\nendfunction\n");
    printf("function automatic [2:0] t5220_interp(input [2:0] ip);\n  case (ip)\n");
    for (int i = 0; i < 8; i++) printf("    3'd%d: t5220_interp = 3'd%d;\n", i, c.interp_coeff[i]);
    printf("  endcase\nendfunction\n");
    // self-check line for the harness
    fprintf(stderr, "energy[1..3] %d %d %d  pitch[1] %d  k0[0] %d k9[7] %d  chirp[0..2] %d %d %d  interp", c.energytable[1], c.energytable[2], c.energytable[3], c.pitchtable[1], c.ktable[0][0], c.ktable[9][7], c.chirptable[0], c.chirptable[1], c.chirptable[2]);
    for (int i = 0; i < 8; i++) fprintf(stderr, " %d", c.interp_coeff[i]);
    fprintf(stderr, "\n");
}
