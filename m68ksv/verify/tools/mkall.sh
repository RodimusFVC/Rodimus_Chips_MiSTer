#!/bin/bash
# Concatenate the RTL into rtl/m68ksv_all.sv (the file the Quartus project reads) and run the Quartus 17.0
# pre-compile grep check from the vault note "Quartus 17.0 SystemVerilog subset" on it.
set -e
HERE=$(dirname "$(realpath "$0")")
R=$HERE/../../rtl
python3 "$R/gen/m68ksv_ucode.py" > /dev/null
{ echo "// m68ksv: all RTL in one file, generated by verify/tools/mkall.sh - edit the sources in rtl/, not this file"
  for f in m68ksv_upkg.sv m68ksv_alu.sv m68ksv_urom.sv m68ksv_drom.sv m68ksv_rf.sv m68ksv_eu.sv m68ksv_biu.sv m68ksv_biu32.sv m68ksv.sv; do
    echo "// ---------------------------------------------------------------- $f"; cat "$R/$f"; done; } > "$R/m68ksv_all.sv"
f=$R/m68ksv_all.sv
echo "== pre-compile check: $f"
echo "-- module-level loops (each must sit inside generate ... endgenerate):"; grep -n -E '^\s*for\s*\(' "$f" || true
echo "-- system-function bounds, size casts, assignment patterns:"; grep -n -E "\\\$(bits|clog2|size)|'\(|'\{" "$f" || true
echo "-- set membership (inside):"; grep -n -w inside "$f" || true
echo "-- bit-select on an expression:"; grep -n -E '\)\s*\[[0-9]' "$f" || true
echo "-- genvar declared inside for (Quartus 17 error 10170; also checks the Quartus top):"
grep -n -E 'for\s*\(\s*genvar' "$f" "$HERE/../../syn/quartus/m68ksv_qtop.sv" || true
echo "== end of check"
