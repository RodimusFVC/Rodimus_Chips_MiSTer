#!/usr/bin/env python3
"""GHDL <-> Verilator co-simulation shims.

For each "kind" below this generates
  shim_<entity>.vhd   the reference entity declaration (copied verbatim from the
                      T48 sources) with an architecture that evaluates a Verilated
                      t48sv model through VHPIDIRECT on every input event, and
                      drives t48_tb_pack.tb_accu_s / tb_istrobe_s from t48sv
  cosim_<kind>.sv     t48sv top + accumulator / instruction-strobe taps
  cosim_glue.cpp      cs_create / cs_eval dispatch
so the unmodified upstream VHDL testbenches run against t48sv.

gen_cosim.py <ref vhdl dir (lineage)> <out dir> <lineage A|B> [--compare]
"""
import os, re, sys

# entity -> (vhdl file rel to ref dir, t48sv module, core path for accu/istrobe or None,
#            {generic value -> t48sv params})
KINDS = {
    't48_core':          ('t48_core.vhd', 't48sv_t48_core', 'u.core.', {}),
    't8039_notri':       ('system/t8039_notri.vhd', 't48sv_t8039_notri', 'u.sys.t48_core_b.core.', {}),
    't8048_notri':       ('system/t8048_notri.vhd', 't48sv_t8048_notri', 'u.sys.t48_core_b.core.', {'ROM_INIT_FILE': '"rom10.hex"'}),
    't8041_notri':       ('system/t8041_notri.vhd', 't48sv_t8041_notri', 'u.sys.upi41_core_b.core.', {'ROM_INIT_FILE': '"rom10.hex"'}),
    't8041a_notri':      ('system/t8041a_notri.vhd', 't48sv_t8041a_notri', 'u.sys.upi41_core_b.core.', {'ROM_INIT_FILE': '"rom10.hex"'}),
    't8042ah_notri':     ('system/t8042ah_notri.vhd', 't48sv_t8042ah_notri', 'u.sys.upi41_core_b.core.', {'ROM_INIT_FILE': '"rom11.hex"'}),
    't8021_notri':       ('system/t8021_notri.vhd', 't48sv_t8021_notri', 'u.t21_core_b.core.', {'ROM_INIT_FILE': '"rom10.hex"'}),
    't8022_notri':       ('system/t8022_notri.vhd', 't48sv_t8022_notri', 'u.t22_core_b.core.', {'ROM_INIT_FILE': '"rom11.hex"'}),
    't8243_sync_notri':  ('t8243/t8243_sync_notri.vhd', 't48sv_t8243_sync_notri', None, {}),
    't8243_async_notri': ('t8243/t8243_async_notri.vhd', 't48sv_t8243_async_notri', None, {}),
}


def strip(v):
    return re.sub(r'--[^\n]*', '', v)


def entity_of(path, name):
    v = strip(open(path).read())
    m = re.search(r'\bentity\s+%s\s+is\b.*?\bend\s+(?:entity\s+)?%s\s*;' % (name, name), v, re.S | re.I)
    text = m.group(0)
    gens = re.findall(r'(\w+)\s*:\s*integer\s*:=\s*(\d+)', text, re.I)
    pm = re.search(r'\bport\s*\((.*)\)\s*;\s*end', text, re.S | re.I)
    ports = []
    for decl in pm.group(1).split(';'):
        mm = re.match(r'\s*([\w\s,]+?)\s*:\s*(in|out)\s+std_logic(?:_vector\s*\(\s*(\d+)\s+downto\s+0\s*\))?', decl, re.I)
        if not mm:
            continue
        for n in mm.group(1).split(','):
            ports.append((n.strip(), mm.group(2).lower(), int(mm.group(3)) + 1 if mm.group(3) else 0))
    return text, gens, ports


# reference-netlist mode: entity -> (core path inside the netlist, {gate: ref config})
REFCFG = {
    'A': {'t48_core': ('', {0: 'R_core'}),
          't8039_notri': ('t48_core_b.', {0: 'R_t8039_notri_g0', 1: 'R_t8039_notri_g1'}),
          't8048_notri': ('t48_core_b.', {0: 'R_t8048_notri_g0', 1: 'R_t8048_notri_g1'})},
    'B': {'t48_core': ('', {0: 'B_core'}),
          't8039_notri': ('t48_core_b.', {0: 'B_t8039_notri_g0', 1: 'B_t8039_notri'}),
          't8048_notri': ('t48_core_b.', {0: 'B_t8048_notri_g0', 1: 'B_t8048_notri'}),
          't8041_notri': ('upi41_core_b.', {0: 'B_t8041_notri_g0', 1: 'B_t8041_notri'}),
          't8041a_notri': ('upi41a_core_b.', {0: 'B_t8041a_notri_g0', 1: 'B_t8041a_notri'}),
          't8042ah_notri': ('upi41a_core_b.', {0: 'B_t8042ah_notri_g0', 1: 'B_t8042ah_notri'}),
          't8021_notri': ('t21_core_b.', {0: 'B_t8021_notri_g0', 1: 'B_t8021_notri'}),
          't8022_notri': ('t22_core_b.', {0: 'B_t8022_notri_g0', 1: 'B_t8022_notri'})},
}

ISTROBE = '''// T48 testbench-only instruction strobe (decoder.vhd), pruned by GHDL synth: rebuilt here
logic is_res_q, is_q, inj_q, ms5_last;
assign ms5_last = %(c)sclock_ctrl_b.mstate_q == 3'd4 && %(c)sdecoder_b.last_cycle_s;
always @(posedge %(c)sdecoder_b.clk_i or negedge %(c)sdecoder_b.res_i)
  if (!%(c)sdecoder_b.res_i) begin is_res_q <= 1'b1; is_q <= 1'b0; inj_q <= 1'b0; end
  else begin
    if (%(c)sdecoder_b.en_clk_i) begin
      if (%(c)sdecoder_b.opc_inj_int_s) inj_q <= 1'b1;
      else if (ms5_last) inj_q <= 1'b0;
      if (ms5_last) is_res_q <= 1'b0;
    end
    if (ms5_last && !inj_q) begin if (!is_res_q) is_q <= 1'b1; end
    else is_q <= 1'b0;
  end
assign tb_accu_o = %(c)salu_b.accumulator_q;
assign tb_istrobe_o = is_q;
'''


def main():
    refmode = '--ref' in sys.argv
    if refmode:
        sys.argv.remove('--ref')
    refdir, out, lineage = sys.argv[1:4]
    os.makedirs(out, exist_ok=True)
    rev = 1 if lineage == 'B' else 0
    glue = ['// generated by gen_cosim.py', '#include <cstdio>', '#include <cstdlib>',
            '#include "verilated.h"']
    cases = []
    kinds = []
    for kid, (ent, (rel, mod, core, extra)) in enumerate(KINDS.items()):
        path = os.path.join(refdir, rel)
        if not os.path.exists(path):
            continue
        text, gens, ports = entity_of(path, ent)
        gate = [g for g, _ in gens if g == 'gate_port_input_g']
        variants = [0, 1] if gate else [0]
        for gv in variants:
            vname = 'cs_%s_g%d' % (ent, gv)
            params = dict(extra)
            if gate:
                params['gate_port_input_g'] = str(gv)
            if mod in ('t48sv_t48_core', 't48sv_t8039_notri', 't48sv_t8048_notri'):
                params['REV2023'] = str(rev)
            par = ', '.join('.%s(%s)' % kv for kv in params.items())
            sv = ['// generated by gen_cosim.py', 'module %s (' % vname]
            decl = []
            for n, d, w in ports:
                decl.append('  %s logic %s%s' % ('input ' if d == 'in' else 'output',
                                                  '[%d:0] ' % (w - 1) if w else '', n))
            decl.append('  output logic [7:0] tb_accu_o')
            decl.append('  output logic tb_istrobe_o')
            sv.append(',\n'.join(decl) + ');')
            conns = ', '.join('.%s(%s)' % (n, n) for n, d, w in ports)
            ref = REFCFG[lineage].get(ent) if refmode else None
            if ref:
                sv.append('%s__%s u (%s);' % (ref[1][gv], ent, conns))
                sv.append(ISTROBE % {'c': 'u.' + ref[0]})
                open(os.path.join(out, vname + '.ref'), 'w').write(ref[1][gv] + '\n')
            else:
                sv.append('%s %s u (%s);' % (mod, '#(%s)' % par if par else '', conns))
            if ref:
                pass
            elif core:
                sv.append('assign tb_accu_o = %salu_b.accu_q;' % core)
                sv.append('assign tb_istrobe_o = %sdecoder_b.istrobe_q;' % core)
            else:
                sv.append("assign tb_accu_o = 8'h00;\nassign tb_istrobe_o = 1'b0;")
            sv.append('endmodule')
            open(os.path.join(out, vname + '.sv'), 'w').write('\n'.join(sv) + '\n')
            kinds.append(vname)
            code = kid * 2 + gv
            ins = [(n, w) for n, d, w in ports if d == 'in']
            outs = [(n, w) for n, d, w in ports if d == 'out']
            glue.append('#include "V%s.h"' % vname)
            body = ['    case %d: {' % code, '      static VerilatedContext *ctx[64];',
                    '      if (!m) { ctx[h] = new VerilatedContext; m = new V%s(ctx[h]); }' % vname,
                    '      V%s *p = (V%s *)m;' % (vname, vname)]
            k = 0
            for n, w in ins:
                if w:
                    body.append('      p->%s = 0;' % n)
                    for b in range(w):
                        body.append('      p->%s |= (bit(i[%d]) << %d);' % (n, k, b))
                        k += 1
                else:
                    body.append('      p->%s = bit(i[%d]);' % (n, k))
                    k += 1
            body.append('      p->eval();')
            rst = [n for n, w in ins if n.startswith('reset')]
            if rst:
                # VHDL runs the async-reset branch at initialisation; give Verilator an edge
                body.append('      if (first) { p->%s ^= 1; p->eval(); p->%s ^= 1; p->eval(); }' % (rst[0], rst[0]))
            k = 0
            for n, w in outs + [('tb_accu_o', 8), ('tb_istrobe_o', 0)]:
                if w:
                    for b in range(w):
                        body.append('      o[%d] = (p->%s >> %d) & 1;' % (k, n, b))
                        k += 1
                else:
                    body.append('      o[%d] = p->%s;' % (k, n))
                    k += 1
            body.append('      break; }')
            cases.append('\n'.join(body))
        # VHDL shim
        ins = [(n, w) for n, d, w in ports if d == 'in']
        outs = [(n, w) for n, d, w in ports if d == 'out']
        V = ['-- generated by gen_cosim.py: %s replaced by t48sv (Verilator) through VHPIDIRECT' % ent,
             'library ieee;', 'use ieee.std_logic_1164.all;', text, '',
             'library ieee;', 'use ieee.std_logic_1164.all;', 'use work.t48_tb_pack.all;',
             'architecture cosim of %s is' % ent,
             '  type iarr is array (0 to 127) of integer;',
             '  function cs_create(kind : integer) return integer is',
             '  begin assert false severity failure; return 0; end;',
             '  attribute foreign of cs_create : function is "VHPIDIRECT cs_create";',
             '  procedure cs_eval(h : integer; i : iarr; o : out iarr) is',
             '  begin assert false severity failure; end;',
             '  attribute foreign of cs_eval : procedure is "VHPIDIRECT cs_eval";',
             '  function b2i(s : std_logic) return integer is',
             '  begin',
             "    case s is when '1' | 'H' => return 1; when '0' | 'L' => return 0; when others => return 2; end case;",
             '  end;',
             '  function i2b(v : integer) return std_logic is',
             "  begin if v = 1 then return '1'; else return '0'; end if; end;",
             'begin',
             '  shim: process (%s)' % ', '.join(n for n, w in ins),
             '    variable i, o : iarr;',
             '    variable h : integer := -1;',
             '  begin',
             '    if h < 0 then h := cs_create(%d%s); end if;' %
             (kid * 2, ' + gate_port_input_g' if any(g == 'gate_port_input_g' for g, _ in gens) else '')]
        k = 0
        for n, w in ins:
            if w:
                for b in range(w):
                    V.append('    i(%d) := b2i(%s(%d));' % (k, n, b))
                    k += 1
            else:
                V.append('    i(%d) := b2i(%s);' % (k, n))
                k += 1
        V.append('    cs_eval(h, i, o);')
        k = 0
        for n, w in outs:
            if w:
                for b in range(w):
                    V.append('    %s(%d) <= i2b(o(%d));' % (n, b, k))
                    k += 1
            else:
                V.append('    %s <= i2b(o(%d));' % (n, k))
                k += 1
        if KINDS[ent][2]:
            for b in range(8):
                V.append('    tb_accu_s(%d) <= i2b(o(%d));' % (b, k + b))
            V.append('    tb_istrobe_s <= i2b(o(%d));' % (k + 8))
        V += ['  end process shim;', 'end cosim;']
        open(os.path.join(out, 'shim_%s.vhd' % ent), 'w').write('\n'.join(V) + '\n')
    glue += ['static void *models[64];', 'static int kinds[64];', 'static int nmodels;',
             'static long unknown_inputs;',
             'static inline int bit(int v) { if (v == 2) unknown_inputs++; return v == 1; }',
             'static void report() { if (unknown_inputs) fprintf(stderr, "COSIM: %ld X/Z/U input samples (mapped to 0)\\n", unknown_inputs); }',
             'extern "C" int cs_create(int kind) {',
             '  if (!nmodels) atexit(report);',
             '  kinds[nmodels] = kind; models[nmodels] = 0; return nmodels++;', '}',
             'extern "C" void cs_eval(int h, const int *i, int *o) {',
             '  void *&m = models[h];', '  bool first = !m;', '  switch (kinds[h]) {'] + cases + \
            ['    default: fprintf(stderr, "bad kind %d\\n", kinds[h]); exit(3);', '  }', '}']
    open(os.path.join(out, 'cosim_glue.cpp'), 'w').write('\n'.join(glue) + '\n')
    open(os.path.join(out, 'kinds.txt'), 'w').write('\n'.join(kinds) + '\n')


if __name__ == '__main__':
    main()
