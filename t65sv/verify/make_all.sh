#!/bin/sh
# make_all.sh: rtl/t65sv_all.sv = core + drop-in top + variant tops (everything except the chip_pool_pkg wrapper)
cd "$(dirname "$0")/../rtl"
{
  echo "// t65sv_all.sv: single-file t65sv (core, T65 drop-in top t65sv_T65, variant tops)."
  echo "// Generated by verify/make_all.sh from t65sv.sv, t65sv816.sv, t65sv_T65.sv, t65sv_variants.sv; edit those."
  echo "//"
  for f in t65sv.sv t65sv816.sv t65sv_T65.sv t65sv_variants.sv; do echo; cat $f; done
} > t65sv_all.sv
echo "t65sv_all.sv: $(wc -l < t65sv_all.sv) lines"
